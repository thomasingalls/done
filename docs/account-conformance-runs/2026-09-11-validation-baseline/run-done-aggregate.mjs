import { spawn, execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, createWriteStream, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const cwd='/private/tmp/done-validation-500630f';
const output=join(cwd,'test-results/aggregate',new Date().toISOString().replaceAll(':','-'));
mkdirSync(output,{recursive:true});
const hash=b=>createHash('sha256').update(b).digest('hex');
const files=execFileSync('git',['ls-files','--cached','--others','--exclude-standard','-z'],{cwd}).toString().split('\0').filter(Boolean);
writeFileSync(join(output,'sources.json'),JSON.stringify(files.map(path=>({path,sha256:hash(readFileSync(join(cwd,path)))})),null,2)+'\n');
const patch=execFileSync('git',['diff','HEAD','--binary'],{cwd,maxBuffer:100*1024*1024});
writeFileSync(join(output,'working.patch'),patch);
const summary={command:'pnpm check',cwd,head:execFileSync('git',['rev-parse','HEAD'],{cwd}).toString().trim(),patchSha256:hash(patch),started:new Date().toISOString(),status:'running',timeoutMs:7200000,env:{CI:'1'},log:'check.log'};
const save=()=>writeFileSync(join(output,'summary.json'),JSON.stringify(summary,null,2)+'\n');save();
console.log('Aggregate evidence: '+output);
const log=createWriteStream(join(output,'check.log'));
const child=spawn('pnpm',['check'],{cwd,env:{...process.env,CI:'1'},detached:true,stdio:['ignore','pipe','pipe']});
for(const stream of [child.stdout,child.stderr])stream.on('data',b=>{log.write(b);process.stdout.write(b)});
let timedOut=false,forced;
const kill=signal=>{try{process.kill(-child.pid,signal)}catch{}};
const deadline=setTimeout(()=>{timedOut=true;kill('SIGTERM');forced=setTimeout(()=>kill('SIGKILL'),5000)},summary.timeoutMs);
const heartbeat=setInterval(()=>console.log('Aggregate still running; '+output+'/check.log'),15000);
const code=await new Promise(resolve=>{child.once('error',e=>{summary.error=String(e);resolve(1)});child.once('close',c=>resolve(c??1))});
clearInterval(heartbeat);clearTimeout(deadline);clearTimeout(forced);
await new Promise(resolve=>log.end(resolve));
Object.assign(summary,{code,timedOut,finished:new Date().toISOString(),status:code===0&&!timedOut?'passed':'failed'});save();
console.log(JSON.stringify(summary));process.exitCode=code||Number(timedOut);
