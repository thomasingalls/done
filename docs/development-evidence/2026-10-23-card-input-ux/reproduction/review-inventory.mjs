import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {buildInventory} from '/Users/thomasingalls/.codex/worktrees/7fda/done/scripts/release-validation/inventory.mjs';
import {compileManifest} from '/Users/thomasingalls/.codex/worktrees/7fda/done/scripts/release-validation/manifest.mjs';
const root='/Users/thomasingalls/.codex/worktrees/7fda/done';
const baseline=process.argv[2];
assert(baseline,'Pass the prior planning snapshot path');
const old=JSON.parse(readFileSync(baseline));
const next=buildInventory(root,JSON.parse(readFileSync(root+'/scripts/release-validation/policy.json')));
const added=['test/compose.test.tsx','test/geometry/card-focus.spec.ts','test/geometry/compose-input.spec.ts','test/geometry/duplicate-card.spec.ts'].sort();
assert.deepEqual(next.tests.filter(t=>!old.tests.some(o=>o.path===t.path)).map(t=>t.path).sort(),added);
const a=structuredClone(old),b=structuredClone(next);
const inputsBefore=new Map(a.inputs.map(t=>[t.path,t.sha256]));
const changedInputs=b.inputs.filter(t=>t.sha256!==inputsBefore.get(t.path));
const allowed=['test/workspaceAdmission.test.ts','test/release-validation/general-tests.test.mjs',...added].sort();
assert.deepEqual(changedInputs.map(t=>t.path).sort(),allowed);
const wa=b.tests.find(t=>t.path==='test/workspaceAdmission.test.ts');
const previous=a.tests.find(t=>t.path===wa.path);
assert.equal(wa.declarations,previous.declarations+4);
assert.deepEqual(wa.propertyFamilies,previous.propertyFamilies.map(f=>({...f,line:f.line+115})));
b.tests=b.tests.filter(t=>!added.includes(t.path));
b.tests[b.tests.findIndex(t=>t.path===wa.path)]=previous;
b.inputs=a.inputs;b.counts.testFiles-=4;b.counts.requiredTestFiles-=4;
assert.deepEqual(b,a);
const manifest=compileManifest(root,next);
const newRows=manifest.rows.filter(r=>added.some(t=>r.id.includes(t)));
assert.equal(newRows.length,4);
assert(newRows.every(r=>r.blocked&&!r.stage),'New files must not receive unreviewed aggregate execution credit');
assert.equal(manifest.status,'blocked');
writeFileSync('/private/tmp/done-ux-20261023-patches/checks-45/inventory-candidate-reviewed.json',JSON.stringify(next,null,2)+'\n');
console.log(JSON.stringify({status:'passed',added,changedInputs:changedInputs.map(t=>t.path),existingTestDelta:{file:wa.path,declarations:4,propertyLines:115,executableCases:25},otherFieldsUnchanged:true,manifestStatus:manifest.status,obligations:manifest.rows.length,unresolved:manifest.unresolved.length,newRows},null,2));
