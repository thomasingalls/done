/**
 * Build the journal seal and emit it as an inlined TypeScript module (§15 row 2).
 *
 * **Why the wasm is inlined rather than fetched.** TRD §12: a fetched module opens
 * a window between the app accepting an edit and the journal being able to seal
 * it, which is the window the journal exists to close. Inlining costs a third more
 * raw bytes as base64 and buys a module that is callable as soon as the bundle has
 * evaluated.
 *
 * **Why the output is generated rather than committed by hand.** Same discipline as
 * the vector files: a base64 blob nobody can regenerate is a build artifact that has
 * quietly stopped matching its source. `--check` fails if the emitted module is not
 * what the current crate produces.
 *
 * **The header binds the source to the blob** (`RC-9`, ratified 2026-08-28, option A
 * at the binding joint). The generated module records the SHA-256 of `src/lib.rs`, of
 * `Cargo.toml` and `Cargo.lock`, and the toolchain version string; check-wasm-seal.mjs
 * recomputes the source-side hashes with Node alone and fails `pnpm check` on mismatch.
 * Round 1's demonstrated mutation — edit `lib.rs`, rebuild nothing — then fails a gate
 * that runs, instead of only `wasm:stale`, which sits in no gate because this builder
 * needs cargo. The binding detects **drift, never forgery**: a builder that lies about
 * these hashes, or a compromised toolchain, is the registered `wasm-toolchain-provenance`
 * debt (`debts.json`, `L-4`), not this header's claim.
 *
 * Usage: node scripts/build-wasm-seal.mjs [--check]
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const crate = join(root, 'wasm/journal-seal');
const wasmPath = join(crate, 'target/wasm32-unknown-unknown/release/journal_seal.wasm');
const out = join(crate, 'seal.generated.ts');
const check = process.argv.includes('--check');

execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: check ? 'pipe' : 'inherit',
});

const wasm = readFileSync(wasmPath);
const b64 = wasm.toString('base64');

const sha256 = (p) => createHash('sha256').update(readFileSync(join(crate, p))).digest('hex');
const toolchain = execFileSync('rustc', ['--version'], { encoding: 'utf8' }).trim();

const module = `/*
 * GENERATED by scripts/build-wasm-seal.mjs — do not edit.
 *
 * XChaCha20-Poly1305 for the crash journal, compiled from the audited RustCrypto
 * \`chacha20poly1305\` crate (wasm/journal-seal). Checked against
 * draft-irtf-cfrg-xchacha-03 §A.3.1 and row 2's composition vectors by
 * scripts/check-wasm-seal.mjs.
 *
 * Source binding, recorded at generation and compared toolchain-free in
 * \`pnpm wasm:verify\` — drift detection only; provenance attestation is the
 * registered L-4 debt (docs/review/remediation/debts.json):
 *   binding src/lib.rs sha256 ${sha256('src/lib.rs')}
 *   binding Cargo.toml sha256 ${sha256('Cargo.toml')}
 *   binding Cargo.lock sha256 ${sha256('Cargo.lock')}
 *   built-by ${toolchain} (recorded, not compared — comparing it needs the toolchain)
 *
 * Raw wasm ${wasm.length} bytes; base64 ${b64.length}; see docs/performance.md for
 * what it weighs through the bundler and what it costs to instantiate.
 */

const WASM_BASE64 =
  '${b64}';

/**
 * Decode, compile and instantiate synchronously.
 *
 * Synchronous throughout, because §12's argument for a WASM seal is that the call
 * stays synchronous. \`new WebAssembly.Module()\` on the main thread is capped at
 * 8 MB in Chromium; this module is three orders of magnitude inside that.
 *
 * The module imports nothing, so the import object is empty — there is no JS on
 * the seal path at all once this has run.
 */
const instantiate = (): WebAssembly.Instance => {
  const binary = Uint8Array.from(atob(WASM_BASE64), (c) => c.charCodeAt(0));
  return new WebAssembly.Instance(new WebAssembly.Module(binary), {});
};

interface Exports {
  memory: WebAssembly.Memory;
  key_ptr: () => number;
  nonce_ptr: () => number;
  aad_ptr: () => number;
  buf_ptr: () => number;
  max_aad: () => number;
  max_plaintext: () => number;
  seal: (aadLen: number, plaintextLen: number) => number;
}

export interface JournalSeal {
  /** ciphertext‖tag, exactly what row 2's record format base64-encodes. */
  seal: (key: Uint8Array, nonce: Uint8Array, aad: Uint8Array, plaintext: Uint8Array) => Uint8Array;
  maxAad: number;
  maxPlaintext: number;
}

/**
 * XChaCha20-Poly1305's widths, which belong to the construction rather than to
 * this module: a 32-byte key and a 24-byte nonce.
 *
 * **The check has to be here, because this is the only boundary that can see a
 * length.** The Rust side reads fixed statics and is handed two lengths, neither
 * of which is the key's or the nonce's; \`memory.set\` of a short input leaves the
 * tail of the previous call in place. An empty nonce after a real one therefore
 * repeats that nonce under the same key, which is precisely what row 2's
 * random-nonce argument may never allow, and a short key produces a record the
 * derived key cannot reopen after a crash. Both are silent without this.
 */
const KEY_BYTES = 32;
const NONCE_BYTES = 24;

export const createJournalSeal = (): JournalSeal => {
  const exports = instantiate().exports as unknown as Exports;
  const maxAad = exports.max_aad();
  const maxPlaintext = exports.max_plaintext();
  const keyAt = exports.key_ptr();
  const nonceAt = exports.nonce_ptr();
  const aadAt = exports.aad_ptr();
  const bufAt = exports.buf_ptr();

  // The memory is never grown by this module — every buffer is a fixed static —
  // so the view is taken once rather than rebuilt on each call.
  const memory = new Uint8Array(exports.memory.buffer);

  return {
    maxAad,
    maxPlaintext,
    seal: (key, nonce, aad, plaintext) => {
      if (key.length !== KEY_BYTES)
        throw new RangeError('journal seal: key must be exactly 32 bytes');
      if (nonce.length !== NONCE_BYTES)
        throw new RangeError('journal seal: nonce must be exactly 24 bytes');
      if (aad.length > maxAad || plaintext.length > maxPlaintext)
        throw new RangeError('journal seal: input exceeds the module buffers');
      memory.set(key, keyAt);
      memory.set(nonce, nonceAt);
      memory.set(aad, aadAt);
      memory.set(plaintext, bufAt);
      const written = exports.seal(aad.length, plaintext.length);
      if (written < 0) throw new Error('journal seal: refused');
      return memory.slice(bufAt, bufAt + written);
    },
  };
};
`;

if (check) {
  const existing = readFileSync(out, 'utf8');
  if (existing !== module) {
    console.error(`${out} is stale — re-run: node scripts/build-wasm-seal.mjs`);
    process.exit(1);
  }
  console.log(`journal seal: generated module matches the crate (${wasm.length} B wasm).`);
} else {
  writeFileSync(out, module);
  const sizes = {
    'raw wasm': wasm.length,
    'wasm gzipped': gzipSync(wasm, { level: 9 }).length,
    base64: b64.length,
    'TS module': module.length,
    'TS module gzipped': gzipSync(Buffer.from(module), { level: 9 }).length,
  };
  for (const [what, bytes] of Object.entries(sizes))
    console.log(`  ${what.padEnd(20)} ${String(bytes).padStart(7)} B`);
}
