/**
 * Check the shipped journal seal against published vectors (TRD §12, §15 row 2).
 *
 * **What this checks, and why it is the generated module rather than the crate.**
 * `wasm/journal-seal/seal.generated.ts` is what a build actually carries — the
 * wasm inlined as base64, plus its glue. Verifying the crate's `target/` artifact
 * would verify something no user receives, and would need a Rust toolchain to run.
 * This runs anywhere Node does, which is what lets it sit inside `pnpm check`.
 *
 * **Two levels, and the outer one is the one that matters.** The composition
 * vectors are the project's own, so agreeing with them proves the module agrees
 * with `@noble`. The `draft-irtf-cfrg-xchacha-03` §A.3.1 KAT is copied from the
 * draft and regenerated by nobody, so it is the only check here that could catch
 * both implementations being wrong together.
 *
 * **Instantiation is synchronous on purpose and that is part of the check.**
 * §12 requires the seal to stay synchronous, so `createJournalSeal()` compiles and
 * instantiates without an await. If that ever stops being possible the import here
 * fails, rather than the property quietly becoming untrue.
 *
 * **The source↔blob binding, compared toolchain-free** (`RC-9`, option A at the
 * binding joint; `S0-8`). The generated module's header records the SHA-256 of
 * `src/lib.rs`, `Cargo.toml` and `Cargo.lock` as they were when the blob was
 * built; this recomputes them with Node alone and fails on mismatch, so editing
 * the crate without rebuilding — round 1's demonstrated mutation, green through
 * every gate at the challenged tip — now fails `pnpm check` with the drifted
 * file named. The claim is **drift detection only**: a builder that lies about
 * the recorded hashes, or a compromised toolchain, is the registered
 * `wasm-toolchain-provenance` debt at `L-4`, which is why the partial claim
 * below owes its remainder there.
 *
 * Usage: node scripts/check-wasm-seal.mjs
 *
 * falsifies: f-9b49b74-wasm-glue-key-nonce-lengths, f-9b49b74-wasm-source-artifact-drift-unchecked -> L-4
 */

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJournalSeal } from '../wasm/journal-seal/seal.generated.ts';
import { installReceipt, setReceiptDetail } from './lib/receipts.mjs';

installReceipt(import.meta.url);

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const published = JSON.parse(readFileSync(join(root, 'test/vectors/journal-aead.json'), 'utf8'));

const unhex = (s) => Uint8Array.from(s.match(/.{2}/gu) ?? [], (b) => Number.parseInt(b, 16));
const hex = (u) => [...u].map((b) => b.toString(16).padStart(2, '0')).join('');

const { seal, maxAad, maxPlaintext } = createJournalSeal();
const failures = [];
let checked = 0;

/* The source↔blob binding. The header's recorded hashes are compared against
 * the crate as it sits on disk — Node alone, no cargo — so a crate edited
 * without a rebuild, or a generated module edited by hand, fails here with the
 * drifted file named. Drift detection only; the toolchain line is recorded,
 * not compared, because comparing it needs the toolchain. */
{
  const crate = join(root, 'wasm/journal-seal');
  const header = readFileSync(join(crate, 'seal.generated.ts'), 'utf8');
  for (const source of ['src/lib.rs', 'Cargo.toml', 'Cargo.lock']) {
    checked += 1;
    const recorded = new RegExp(`^ \\* {3}binding ${source.replace(/[./]/gu, '\\$&')} sha256 ([0-9a-f]{64})$`, 'mu').exec(header)?.[1];
    if (recorded === undefined) {
      failures.push(`seal.generated.ts records no binding hash for ${source} — regenerate: node scripts/build-wasm-seal.mjs`);
      continue;
    }
    const current = createHash('sha256').update(readFileSync(join(crate, source))).digest('hex');
    if (current !== recorded) {
      failures.push(
        `${source} is ${current.slice(0, 16)}… and the shipped module was built from ${recorded.slice(0, 16)}… — ` +
          'the source drifted from the blob (or the header was edited alone). Rebuild: node scripts/build-wasm-seal.mjs',
      );
    }
  }
}

/* The external KAT — the only vector here whose origin is outside this repo. */
{
  const kat = published.primitive_kat;
  const got = seal(
    unhex(kat.key),
    unhex(kat.nonce),
    unhex(kat.aad),
    new TextEncoder().encode(kat.plaintext_utf8),
  );
  checked += 1;
  const ciphertext = hex(got.subarray(0, 16));
  const tag = hex(got.subarray(got.length - 16));
  if (ciphertext !== kat.ciphertext_first_16)
    failures.push(
      `${kat.source}: ciphertext starts ${ciphertext}, expected ${kat.ciphertext_first_16}`,
    );
  if (tag !== kat.tag) failures.push(`${kat.source}: tag ${tag}, expected ${kat.tag}`);
}

/*
 * The composition vectors. The expectation is decoded back out of the published
 * record rather than stored beside it, so this checks the bytes the journal
 * actually writes — "2:" || base64(u32be(gen) || nonce[24] || ciphertext || tag).
 */
for (const vector of published.vectors) {
  const raw = Buffer.from(vector.expected.record.slice(2), 'base64');
  const expected = hex(raw.subarray(4 + 24));
  const got = hex(
    seal(
      unhex(vector.derived.k_journal),
      unhex(vector.inputs.nonce),
      unhex(vector.derived.aad),
      unhex(vector.inputs.plaintext),
    ),
  );
  checked += 1;
  if (got !== expected) failures.push(`${vector.name}: got ${got}, expected ${expected}`);
}

/* The length guard is the module's only failure path, so it is checked in both
 * directions: the largest accepted input seals, and one byte more is refused. */
for (const [what, aad, plaintext] of [
  ['aad', maxAad + 1, 0],
  ['plaintext', 0, maxPlaintext + 1],
]) {
  checked += 1;
  try {
    seal(new Uint8Array(32), new Uint8Array(24), new Uint8Array(aad), new Uint8Array(plaintext));
    failures.push(`oversize ${what} was accepted`);
  } catch {
    /* expected */
  }
}
checked += 1;
try {
  const out = seal(
    new Uint8Array(32),
    new Uint8Array(24),
    new Uint8Array(maxAad),
    new Uint8Array(maxPlaintext),
  );
  if (out.length !== maxPlaintext + 16)
    failures.push('the largest accepted input sealed to a wrong length');
} catch (error) {
  failures.push(`the largest accepted input was refused: ${error.message}`);
}

/* The key and the nonce have no length argument, so the module cannot check
 * them and the wrapper is the only place that can. Every width other than the
 * construction's own is refused before a single byte reaches WASM memory. */
for (const [what, key, nonce] of [
  ['an empty key', 0, 24],
  ['a short key', 31, 24],
  ['a long key', 33, 24],
  ['an empty nonce', 32, 0],
  ['a short nonce', 32, 23],
  ['a long nonce', 32, 25],
]) {
  checked += 1;
  try {
    seal(new Uint8Array(key), new Uint8Array(nonce), new Uint8Array(0), new Uint8Array(8));
    failures.push(`${what} was accepted`);
  } catch {
    /* expected */
  }
}

/* The regression this guard exists for, stated as the sequence that produced it:
 * a real call stages 32 key bytes and 24 nonce bytes into statics that nothing
 * clears, so a following call with an empty nonce reused all 24 of them and
 * returned byte-identical ciphertext under the same key. That is nonce reuse
 * with no symptom. It must now refuse, and the first call must still be intact
 * afterwards. */
checked += 1;
{
  const key = new Uint8Array(32).fill(7);
  const nonce = new Uint8Array(24).fill(9);
  const plaintext = new Uint8Array(8).fill(1);
  const first = hex(seal(key, nonce, new Uint8Array(0), plaintext));
  try {
    seal(key, new Uint8Array(0), new Uint8Array(0), plaintext);
    failures.push('an empty nonce after a real one was accepted — stale nonce bytes are reachable');
  } catch {
    /* expected */
  }
  if (hex(seal(key, nonce, new Uint8Array(0), plaintext)) !== first)
    failures.push('a refused call disturbed the staged state of the next good one');
}

if (failures.length > 0) {
  setReceiptDetail({ failures });
  console.error(`journal seal: ${failures.length} of ${checked} checks FAILED`);
  for (const failure of failures) console.error(`  ${failure}`);
  process.exit(1);
}

console.log(
  `journal seal: ${checked} checks pass — the published KAT, ${published.vectors.length} composition vectors, the length guard in both directions, the key/nonce width guard, and the source↔blob binding (lib.rs, Cargo.toml, Cargo.lock hashes match the generated header — drift detection only; provenance attestation is the registered L-4 debt).`,
);
