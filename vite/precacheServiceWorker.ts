/**
 * A hand-rolled, precache-only service worker (TRD §1).
 *
 * Written as a plugin rather than a static file because the precache list is
 * the build's own hashed output, and a hand-maintained list is a stale list.
 * There is no runtime caching strategy to configure, which is the whole reason
 * this is ten lines of plugin instead of a dependency.
 */

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Plugin } from 'vite';

const CACHEABLE = /\.(?:js|css|html|svg|png|webmanifest|woff2?)$/;

const serviceWorkerSource = (
  base: string,
  version: string,
  precache: string[],
  integrity: Record<string, string>,
): string => `
// Generated by vite/precacheServiceWorker.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const PREFIX = 'done-precache-v2-' + encodeURIComponent(BASE) + '-';
const CACHE = PREFIX + VERSION;
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const URLS = new Set(PRECACHE.map((path) => new URL(path, self.location.origin).href));
const INTEGRITY = ${JSON.stringify(integrity)};
// These are this build's static assets. Vary: Origin from a static host must not
// distinguish installation fetches from crossorigin module/style requests.
const cached = (request) => caches.open(CACHE).then((cache) => cache.match(request, { ignoreVary: true }));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    // Verify the entire release before publishing any entries. A 200 HTML fallback,
    // stale public asset or interrupted server switch must not install a mixed build.
    const responses = await Promise.all(PRECACHE.map(async (path) => {
      const response = await fetch(path, { cache: 'no-store', redirect: 'error' });
      if (!response.ok) throw new Error('Incomplete application download');
      const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
      const hex = Array.from(new Uint8Array(digest), (n) => n.toString(16).padStart(2, '0')).join('');
      if (hex !== INTEGRITY[path]) throw new Error('Application download does not match this release');
      return response;
    }));
    const cache = await caches.open(CACHE);
    try {
      for (let i = 0; i < PRECACHE.length; i++) await cache.put(PRECACHE[i], responses[i]);
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
    // Use the browser's waiting phase. Existing pages retain their worker and assets
    // until every controlled tab/window closes; no reload or storage migration here.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key)))),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  // The staged Local entry must cold-open its own shell, never the legacy editor.
  if (request.mode === 'navigate') {
    const shell = new URL(request.url).pathname === BASE + 'local.html' ? 'local.html' : 'index.html';
    event.respondWith(
      cached(BASE + shell).then((response) => response || fetch(request)),
    );
    return;
  }

  if (URLS.has(request.url)) {
    event.respondWith(cached(request).then((response) => response || fetch(request)));
  }
});
`;

export const precacheServiceWorker = (): Plugin => {
  let base = '/';

  return {
    name: 'done:precache-service-worker',
    apply: 'build',

    configResolved(config) {
      base = config.base;
    },

    writeBundle(options) {
      if (!options.dir) throw new Error('Precache generation requires an output directory.');
      const directory = options.dir;
      // Vite removes inlined entry chunks after our old generateBundle hook. Read the final
      // written output, including copied public assets, so no missing chunk can enter the cache.
      const files = readdirSync(directory, { recursive: true, encoding: 'utf8' })
        .filter(
          (name) =>
            name !== 'sw.js' && CACHEABLE.test(name) && statSync(join(directory, name)).isFile(),
        )
        .sort();
      if (!files.includes('index.html') || !files.includes('local.html'))
        throw new Error('Both application entries must exist before precaching.');
      const entries = [base, ...files.map((name) => `${base}${name.replaceAll('\\', '/')}`)];
      const hashes = files.map(
        (name) =>
          [
            name,
            createHash('sha256')
              .update(readFileSync(join(directory, name)))
              .digest('hex'),
          ] as const,
      );
      const integrity = Object.fromEntries([
        [base, hashes.find(([name]) => name === 'index.html')![1]],
        ...hashes.map(([name, hash]) => [`${base}${name.replaceAll('\\', '/')}`, hash]),
      ]);
      // HTML, manifests and public icons have stable names: their byte changes must also produce
      // a new worker/cache version, even when the hashed JavaScript filenames remain the same.
      const version = createHash('sha256')
        .update(JSON.stringify([base, hashes]))
        // A worker-policy change also needs a fresh cache, even if app bytes stay fixed.
        .update(serviceWorkerSource.toString())
        .digest('hex')
        .slice(0, 12);
      writeFileSync(
        join(directory, 'sw.js'),
        serviceWorkerSource(base, version, entries, integrity),
      );
    },
  };
};
